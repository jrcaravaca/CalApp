export function translateCommonFoodName(name: string): string {
  const normalized = name.trim().toLocaleLowerCase('en');
  if (COMMON_FOOD_TRANSLATIONS[normalized]) return COMMON_FOOD_TRANSLATIONS[normalized];

  const withoutPreparation = normalized
    .replace(/\([^)]*\)/g, ' ')
    .replace(/\b(raw|cooked|grilled|roasted|baked|boiled|fresh|frozen|boneless|skinless)\b/g, ' ')
    .replace(/[,:;–—-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  return COMMON_FOOD_TRANSLATIONS[withoutPreparation] || name;
}