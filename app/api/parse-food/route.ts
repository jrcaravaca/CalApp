import { NextRequest, NextResponse } from 'next/server';
import { GoogleGenAI } from '@google/genai';
import { AIParsedMealResponse } from '@/lib/types';

// Enforce server-side execution only
export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

export async function POST(req: NextRequest) {
  try {
    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      return NextResponse.json(
        { error: 'Server configuration error: GEMINI_API_KEY is not defined.' },
        { status: 500 }
      );
    }

    const body = await req.json();
    const { text, image, meal_type } = body;

    if (!text && !image) {
      return NextResponse.json(
        { error: 'Please provide either a meal description text or an image.' },
        { status: 400 }
      );
    }

    const ai = new GoogleGenAI({ apiKey });

    const promptInstructions = `
You are an expert nutritionist and precise food tracking AI engine for "FitFree", a premium fitness & macro application like Fitia.
Analyze the user's meal input (text and/or photo).
Identify every distinct ingredient or food component.
Estimate realistic portion weights in grams (g) based on standard culinary servings or visual cues.
Provide standard nutritional values per 100g for each component and compute the total calories and macros for that serving.

Return a STRICT JSON object with this exact structure:
{
  "meal_name": "Nombre breve en español (por ejemplo, Avena con proteína y plátano)",
  "items": [
    {
      "name": "Nombre del alimento en español (por ejemplo, Copos de avena)",
      "serving_grams": 50,
      "calories_100g": 389,
      "protein_100g": 16.9,
      "carbs_100g": 66.3,
      "fat_100g": 6.9,
      "total_calories": 194.5,
      "total_protein": 8.5,
      "total_carbs": 33.2,
      "total_fat": 3.5,
      "notes": "Descripción breve en español"
    }
  ],
  "total_meal_calories": 450,
  "total_meal_protein": 35.5,
  "total_meal_carbs": 55.0,
  "total_meal_fat": 8.0,
  "analysis_notes": "Comentario breve en español"
}

Ensure all numerical values are positive numbers (no strings).
Write meal_name, every item name, notes, and analysis_notes in Spanish, even when the food has an English name in the input. Preserve brand names as written.
If the input is not food, return items as an empty array [] and explain in analysis_notes.
`;

    const contents: any[] = [];

    if (image) {
      let mimeType = 'image/jpeg';
      let base64Data = image;

      if (image.startsWith('data:')) {
        const matches = image.match(/^data:([a-zA-Z0-9]+\/[a-zA-Z0-9-.+]+);base64,(.+)$/);
        if (matches) {
          mimeType = matches[1];
          base64Data = matches[2];
        } else {
          const parts = image.split(',');
          base64Data = parts[1] || parts[0];
        }
      }

      contents.push({
        inlineData: {
          mimeType,
          data: base64Data,
        },
      });
    }

    const userPrompt = text
      ? `User meal description (${meal_type || 'meal'}): "${text}"\n\n${promptInstructions}`
      : `Analyze the food in this image (${meal_type || 'meal'}).\n\n${promptInstructions}`;

    contents.push(userPrompt);

    // Primary model is gemini-2.5-flash as specified by user requirements
    // with automatic retry on temporary high-demand 503 spikes
    const candidateModels = ['gemini-2.5-flash', 'gemini-2.5-flash-lite'];
    let lastError: any = null;
    let rawText = '';

    for (const model of candidateModels) {
      try {
        const response = await ai.models.generateContent({
          model,
          contents,
          config: {
            responseMimeType: 'application/json',
          },
        });
        rawText = response.text || '';
        if (rawText) break;
      } catch (err: any) {
        lastError = err;
        console.warn(`Model ${model} failed, attempting next if available:`, err.message || err);
        // Wait 800ms before retrying in case of demand spike
        await new Promise((r) => setTimeout(r, 800));
      }
    }

    if (!rawText) {
      throw lastError || new Error('No response generated by Gemini model');
    }

    // Clean any markdown formatting if present
    let cleaned = rawText.trim();
    if (cleaned.startsWith('```json')) {
      cleaned = cleaned.replace(/^```json\s*/, '').replace(/\s*```$/, '');
    } else if (cleaned.startsWith('```')) {
      cleaned = cleaned.replace(/^```\s*/, '').replace(/\s*```$/, '');
    }

    const parsed: AIParsedMealResponse = JSON.parse(cleaned);

    // Recalculate totals if missing or verify math
    if (!parsed.items) {
      parsed.items = [];
    }

    let sumCal = 0;
    let sumP = 0;
    let sumC = 0;
    let sumF = 0;

    parsed.items = parsed.items.map((item) => {
      const g = Number(item.serving_grams) || 100;
      const c100 = Number(item.calories_100g) || 0;
      const p100 = Number(item.protein_100g) || 0;
      const carb100 = Number(item.carbs_100g) || 0;
      const f100 = Number(item.fat_100g) || 0;

      const total_cal = Math.round((c100 * g) / 100);
      const total_p = Math.round(((p100 * g) / 100) * 10) / 10;
      const total_c = Math.round(((carb100 * g) / 100) * 10) / 10;
      const total_f = Math.round(((f100 * g) / 100) * 10) / 10;

      sumCal += total_cal;
      sumP += total_p;
      sumC += total_c;
      sumF += total_f;

      return {
        name: item.name || 'Food Item',
        serving_grams: g,
        calories_100g: Math.round(c100 * 10) / 10,
        protein_100g: Math.round(p100 * 10) / 10,
        carbs_100g: Math.round(carb100 * 10) / 10,
        fat_100g: Math.round(f100 * 10) / 10,
        total_calories: total_cal,
        total_protein: total_p,
        total_carbs: total_c,
        total_fat: total_f,
        notes: item.notes || '',
      };
    });

    parsed.total_meal_calories = Math.round(sumCal);
    parsed.total_meal_protein = Math.round(sumP * 10) / 10;
    parsed.total_meal_carbs = Math.round(sumC * 10) / 10;
    parsed.total_meal_fat = Math.round(sumF * 10) / 10;

    return NextResponse.json(parsed);
  } catch (error: any) {
    console.error('Error in /api/parse-food:', error);
    return NextResponse.json(
      {
        error: error.message || 'Failed to analyze food intake. Please try again.',
      },
      { status: 500 }
    );
  }
}
